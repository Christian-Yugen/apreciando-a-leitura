create type public.user_role as enum ('user', 'admin');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text,
  role public.user_role not null default 'user',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.reviews (
  id bigint generated by default as identity primary key,
  "legacyId" text unique,
  slug varchar(190),
  title varchar(255) not null,
  author varchar(255) not null,
  genre varchar(255),
  labels jsonb,
  "reviewDate" timestamptz not null,
  content text not null,
  "coverImageUrl" text,
  "purchaseLink" text,
  "sourceUrl" text,
  excerpt text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table public.books (
  id bigint generated by default as identity primary key,
  title varchar(255) not null,
  synopsis text not null,
  "coverImageUrl" text,
  "purchaseLink" text,
  series varchar(255),
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table public.contact_requests (
  id bigint generated always as identity primary key,
  name text not null check (char_length(name) between 2 and 120),
  email text not null,
  subject text not null check (char_length(subject) between 2 and 200),
  message text not null check (char_length(message) between 10 and 5000),
  created_at timestamptz not null default now()
);

create table public.quote_requests (
  id bigint generated always as identity primary key,
  name text not null check (char_length(name) between 2 and 120),
  email text not null,
  "serviceType" text not null,
  "wordCount" text,
  description text not null check (char_length(description) between 10 and 5000),
  created_at timestamptz not null default now()
);

create index reviews_review_date_idx on public.reviews ("reviewDate" desc);
create index reviews_genre_idx on public.reviews (genre);

alter table public.profiles enable row level security;
alter table public.reviews enable row level security;
alter table public.books enable row level security;
alter table public.contact_requests enable row level security;
alter table public.quote_requests enable row level security;

create policy "Public reviews are readable" on public.reviews for select using (true);
create policy "Public books are readable" on public.books for select using (true);
create policy "Users read their profile" on public.profiles for select to authenticated using ((select auth.uid()) = id);
create policy "Users update their profile" on public.profiles for update to authenticated using ((select auth.uid()) = id);
create policy "Anyone can send contact requests" on public.contact_requests for insert to anon, authenticated with check (true);
create policy "Anyone can send quote requests" on public.quote_requests for insert to anon, authenticated with check (true);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'name', new.raw_user_meta_data ->> 'full_name'));
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

